#!/usr/bin/env bash
# Remove what deploy/org/install.sh placed, and nothing else. Run as an administrator (sudo).
# Copilot CLI: /etc/github-copilot/catpilot-guardrails/ and policy.d/catpilot-guardrails.json under the same rules.
# Removes the hooks, as the zipapp catpilot-guard.pyz with its recorded SHA-256 or as hook copies with the
# catpilot_guard package beside them (all under <managed dir>/catpilot-guardrails/), the skills it installed, and the
# managed files only when they are byte-for-byte what install.sh writes for the given server URL, in either layout,
# with or without --overlay; a managed file you
# have since edited or merged is left in place and named, so you can remove our keys by hand.
# It removes /etc/codex/catpilot-guardrails/ (the Codex hooks and their package, and from an --overlay install the
# session-start script and rules) and /etc/codex/requirements.toml under the same byte-for-byte rule, with or
# without the session-start hook and the company-rules hook; the compiled company policy goes with
# catpilot-guardrails/. A tool's catpilot-guardrails/hooks/ stays while a kept managed file still runs
# hooks from it. From an --overlay install it also removes the marked catpilot-company-rules
# section of the managed CLAUDE.md, deleting that file only when nothing else is in it.
#
#   sudo deploy/org/uninstall.sh --server-url https://mcp.example.com/mcp
set -euo pipefail
SERVER_URL=""
while [ $# -gt 0 ]; do
  case "$1" in
    --server-url) SERVER_URL="$2"; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
[ -n "$SERVER_URL" ] || { echo "--server-url is required (the URL you installed with)" >&2; exit 2; }
if [ "${CATPILOT_ALLOW_NONROOT:-0}" != "1" ]; then
  [ "$(id -u)" -eq 0 ] || { echo "run with sudo" >&2; exit 2; }
fi
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
case "$(uname -s)" in
  Darwin) DEFAULT_CC_DIR="/Library/Application Support/ClaudeCode" ;;
  Linux) DEFAULT_CC_DIR="/etc/claude-code" ;;
  *) echo "unsupported OS: $(uname -s)" >&2; exit 2 ;;
esac
CC_DIR="${CATPILOT_CC_DIR:-$DEFAULT_CC_DIR}"
CODEX_DIR="${CATPILOT_CODEX_DIR:-/etc/codex}"
COPILOT_DIR="${CATPILOT_COPILOT_DIR:-/etc/github-copilot}"
# A trailing slash would keep the paths written into managed files from matching the ones checked and rewritten.
no_trailing_slash() { local d="$1"; while [ "${d%/}" != "$d" ]; do d="${d%/}"; done; printf '%s' "${d:-/}"; }
CC_DIR="$(no_trailing_slash "$CC_DIR")"; CODEX_DIR="$(no_trailing_slash "$CODEX_DIR")"
COPILOT_DIR="$(no_trailing_slash "$COPILOT_DIR")"
RULES_FILES="$REPO/deploy/org/session_start_files.py"
# shellcheck source=interpreter.sh
. "$REPO/deploy/org/interpreter.sh"
# The interpreter install.sh recorded in the hook commands, which the managed files are compared with; an install
# before it recorded one names python3.
RECORDED_PYTHON="$(recorded_interpreter "$CC_DIR/managed-settings.json" "$CODEX_DIR/requirements.toml" "$COPILOT_DIR/policy.d/catpilot-guardrails.json")"
PYTHON_BIN="${PYTHON_BIN:-${RECORDED_PYTHON:-python3}}"
# The session-start pieces are generated by Python, as install.sh generates them; without a working
# interpreter they cannot be recomputed, so the files that hold them are kept and named.
PYTHON_OK=0
"$PYTHON_BIN" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' >/dev/null 2>&1 && PYTHON_OK=1

# remove_if_ours FILE HINT CONTENT...: remove FILE when it is one of the contents install.sh may have written there.
# A file that does not mention catpilot was never ours and is not mentioned.
remove_if_ours() {
  local file="$1" hint="$2" content expected compared=0
  shift 2
  [ -e "$file" ] || return 0
  grep -q catpilot "$file" 2>/dev/null || return 0
  content="$(cat "$file")"
  for expected in "$@"; do
    [ -n "$expected" ] || continue
    compared=1
    if [ "$content" = "$expected" ]; then rm -f "$file"; echo "removed $file"; return 0; fi
  done
  if [ "$compared" -eq 1 ]; then
    echo "kept    $file (edited since install; $hint)"
  else
    echo "kept    $file ($PYTHON_BIN could not run, so it was not compared with what install.sh writes; $hint)"
  fi
}
SETTINGS_JSON="$(sed -e "s#https://mcp.example.com/mcp#$SERVER_URL#" -e "s#/Library/Application Support/ClaudeCode#$CC_DIR#g" "$REPO/deploy/org/claude-code/managed-settings.json")"
# What install.sh may have written: each variant, with the recorded interpreter and with python3 (an earlier install).
SETTINGS_CANDIDATES=("$SETTINGS_JSON")
REQUIREMENTS_CANDIDATES=()
COPILOT_CANDIDATES=()
[ "$PYTHON_OK" -eq 1 ] && managed_candidates "$SETTINGS_JSON"
remove_if_ours "$CC_DIR/managed-settings.json" \
  "remove the catpilot keys by hand: the hooks entries that run catpilot-guardrails/hooks/, SessionStart and the company-rules hook included, and managedMcpServers.catpilot-guardrails" \
  "${SETTINGS_CANDIDATES[@]}"
MCP_JSON="$(sed -e "s#https://mcp.example.com/mcp#$SERVER_URL#" "$REPO/deploy/org/claude-code/managed-mcp.json")"
remove_if_ours "$CC_DIR/managed-mcp.json" "remove the catpilot keys by hand" "$MCP_JSON"
CODEX_TOML="$(sed -e "s#https://mcp.example.com/mcp#$SERVER_URL#" "$REPO/deploy/org/codex/managed_config.toml")"
remove_if_ours "$CODEX_DIR/managed_config.toml" "remove the catpilot keys by hand" "$CODEX_TOML"
remove_if_ours "$CODEX_DIR/requirements.toml" \
  "remove by hand the [hooks] managed_dir that names catpilot-guardrails, the [[hooks.PreToolUse]] entries that run catpilot-guardrails/hooks/, the [[hooks.SessionStart]] entry that runs catpilot-company-rules.py, and [features].hooks = true unless you want it" \
  ${REQUIREMENTS_CANDIDATES[@]+"${REQUIREMENTS_CANDIDATES[@]}"}

remove_if_ours "$COPILOT_DIR/policy.d/catpilot-guardrails.json" \
  "remove the PreToolUse entries that run catpilot-guardrails/hooks/, or the file if nothing else is in it" \
  ${COPILOT_CANDIDATES[@]+"${COPILOT_CANDIDATES[@]}"}

# The managed CLAUDE.md: only the marked section is ours.
if [ -e "$CC_DIR/CLAUDE.md" ] || [ -L "$CC_DIR/CLAUDE.md" ]; then
  if [ "$PYTHON_OK" -eq 1 ]; then
    "$PYTHON_BIN" "$RULES_FILES" claude-md-remove --target "$CC_DIR/CLAUDE.md"
  elif grep -qF '<!-- catpilot-company-rules:begin -->' "$CC_DIR/CLAUDE.md" 2>/dev/null; then
    echo "kept    $CC_DIR/CLAUDE.md ($PYTHON_BIN could not run; delete the lines from <!-- catpilot-company-rules:begin --> to <!-- catpilot-company-rules:end --> by hand)"
  fi
fi

# A managed file kept above may still run hooks from catpilot-guardrails/hooks/. Removing the scripts under it
# would leave every command it covers running a missing file: python3 exits 2, which blocks every command or
# file write on Claude Code and Codex, or the host skips a hook it cannot load. So that tool's hooks/ directory
# stays while the file mentions catpilot-guardrails at all, however the path is spelled there (escaped slashes,
# split quotes, a cd first): leaving files behind is the safe failure. The rest of catpilot-guardrails/ (the rules)
# is removed.
keep_hooks_for() {  # FILE...: true when any of them mentions catpilot-guardrails
  local f
  for f in "$@"; do
    [ -e "$f" ] && grep -qF "catpilot-guardrails" "$f" 2>/dev/null && return 0
  done
  return 1
}
for d in "$CC_DIR/catpilot-guardrails" "$CODEX_DIR/catpilot-guardrails" "$COPILOT_DIR/catpilot-guardrails"; do
  case "$d" in
    "$CC_DIR/catpilot-guardrails") file="$CC_DIR/managed-settings.json" ;;
    "$CODEX_DIR/catpilot-guardrails") file="$CODEX_DIR/requirements.toml" ;;
    *) file="$COPILOT_DIR/policy.d/catpilot-guardrails.json" ;;
  esac
  # On Copilot CLI any policy.d/*.json file may run the hooks, not only the one install.sh wrote.
  if [ "$d" = "$COPILOT_DIR/catpilot-guardrails" ]; then
    set -- "$COPILOT_DIR"/policy.d/*.json; file="a file in $COPILOT_DIR/policy.d/"
  else
    set -- "$file"
  fi
  if [ -d "$d/hooks" ] && keep_hooks_for "$@"; then
    find "$d" -mindepth 1 -maxdepth 1 ! -name hooks -exec rm -rf {} +
    echo "kept    $d/hooks ($file still runs hooks from it; remove those hook entries from it, then run uninstall.sh again)"
  elif [ -e "$d" ]; then
    rm -rf "$d"; echo "removed $d"
  fi
done
for d in "$CC_DIR"/.claude/skills/catpilot-safe-building* \
         "$CC_DIR/.claude/skills/catpilot-security-core" \
         "$CC_DIR/.claude/skills/catpilot-agentic-security" \
         "$CODEX_DIR"/skills/catpilot-safe-building* \
         "$CODEX_DIR/skills/catpilot-security-core" \
         "$CODEX_DIR/skills/catpilot-agentic-security"; do
  [ -e "$d" ] && { rm -rf "$d"; echo "removed $d"; } || true
done
echo "Done. Per-user evidence logs under ~/.catpilot-guardrails/ are left in place."
